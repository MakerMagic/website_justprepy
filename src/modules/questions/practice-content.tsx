import Image from "next/image";
import { renderToString } from "katex";
import type { PracticeContent, PracticeContentPart } from "./practice.types";

/** Delimited inline/display LaTeX is supported alongside existing plain text. */
export function contentParts(content: PracticeContent): PracticeContentPart[] {
  if (typeof content !== "string") return content;
  const pattern =
    /(?<!\\)(\$\$([\s\S]+?)\$\$|\$([^$\n]+?)\$|\\\(([\s\S]+?)\\\)|\\\[([\s\S]+?)\\\])/g;
  const parts: PracticeContentPart[] = [];
  let cursor = 0;
  for (const match of content.matchAll(pattern)) {
    if (match.index > cursor)
      parts.push({ type: "text", text: content.slice(cursor, match.index) });
    parts.push({
      type: "math",
      latex: match[2] ?? match[3] ?? match[4] ?? match[5],
      display: Boolean(match[2] ?? match[5]),
    });
    cursor = match.index + match[0].length;
  }
  if (cursor < content.length)
    parts.push({ type: "text", text: content.slice(cursor) });
  return parts;
}

/** The only markup boundary is MathML generated by KaTeX; source HTML is never injected. */
export function latexMathML(latex: string, display = false): string | null {
  if (
    latex.length > 20000 ||
    /\\(?:href|url|includegraphics|html\w*)\b/.test(latex)
  )
    return null;
  try {
    return renderToString(latex, {
      output: "mathml",
      displayMode: display,
      trust: false,
      strict: "error",
      throwOnError: true,
      maxExpand: 1000,
      maxSize: 10,
      macros: {},
    });
  } catch {
    return null;
  }
}

export function PracticeContentView({ content }: { content: PracticeContent }) {
  return (
    <span className="practice-rich-content">
      {contentParts(content).map((part, index) => {
        if (part.type === "text")
          return (
            <span key={index} className="practice-rich-text">
              {part.text.replace(/\\\$/g, "$")}
            </span>
          );
        if (part.type === "math") {
          const markup = latexMathML(part.latex, part.display);
          return markup ? (
            <span
              key={index}
              className={"practice-math" + (part.display ? " is-display" : "")}
              dangerouslySetInnerHTML={{ __html: markup }}
            />
          ) : (
            <span key={index} className="content-unavailable">
              Mathematical expression unavailable.
            </span>
          );
        }
        const safeSource = /^(\/(?!\/)|https:\/\/)/.test(part.src);
        if (!safeSource || part.width <= 0 || part.height <= 0)
          return (
            <span key={index} className="content-unavailable">
              Image unavailable.
            </span>
          );
        return (
          <span
            key={index}
            className="practice-content-image"
            style={{ maxWidth: part.width }}
          >
            <Image
              unoptimized
              src={part.src}
              alt={part.alt}
              width={part.width}
              height={part.height}
            />
            {part.caption && (
              <span className="practice-image-caption">{part.caption}</span>
            )}
          </span>
        );
      })}
    </span>
  );
}
